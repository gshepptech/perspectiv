-- Writers a member follows: a new story by the writer notifies the follower
-- (NOTIFICATION_KIND_NEW_STORY_BY_FOLLOWED_WRITER). Blocking either way
-- removes the follow in both directions.
CREATE TABLE IF NOT EXISTS user_follows (
    follower_id uuid        NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    followee_id uuid        NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    created_at  timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (follower_id, followee_id),
    CONSTRAINT user_follows_not_self CHECK (follower_id <> followee_id)
);
-- Fan-out and the profile's follower count read followers by writer.
CREATE INDEX IF NOT EXISTS user_follows_followee_idx ON user_follows (followee_id);

