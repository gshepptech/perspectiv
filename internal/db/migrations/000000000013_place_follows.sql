-- Places a user follows: a new story at the place or anywhere under it
-- notifies them (NOTIFICATION_KIND_NEW_STORY_AT_FOLLOWED_PLACE).
CREATE TABLE IF NOT EXISTS place_follows (
    user_id    uuid        NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    place_id   uuid        NOT NULL REFERENCES places (id) ON DELETE CASCADE,
    created_at timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (user_id, place_id)
);
-- Fan-out reads followers by place.
CREATE INDEX IF NOT EXISTS place_follows_place_idx ON place_follows (place_id);

